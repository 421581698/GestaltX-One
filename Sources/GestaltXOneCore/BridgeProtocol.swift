import Foundation

public enum BridgeAction: String, Codable, CaseIterable, Sendable {
    case deviceGetInfo = "device.getInfo"
    case deviceGetCapabilities = "device.getCapabilities"
    case deviceGetPairingStatus = "device.getPairingStatus"
    case backupGetStatus = "backup.getStatus"
    case taskGetStatus = "task.getStatus"
}

public struct BridgeRequest: Codable, Sendable {
    public let version: Int
    public let requestID: UUID
    public let action: BridgeAction
    public let payload: [String: String]
    public let nonce: String

    public init(
        version: Int = 1,
        requestID: UUID = UUID(),
        action: BridgeAction,
        payload: [String: String] = [:],
        nonce: String
    ) {
        self.version = version
        self.requestID = requestID
        self.action = action
        self.payload = payload
        self.nonce = nonce
    }
}

public struct BridgeResponse: Codable, Sendable {
    public let version: Int
    public let requestID: UUID
    public let success: Bool
    public let status: String
    public let data: [String: String]
    public let error: String?

    public init(
        requestID: UUID,
        success: Bool,
        status: String,
        data: [String: String] = [:],
        error: String? = nil
    ) {
        self.version = 1
        self.requestID = requestID
        self.success = success
        self.status = status
        self.data = data
        self.error = error
    }

    public static func rejected(_ requestID: UUID, reason: String) -> Self {
        .init(requestID: requestID, success: false, status: "rejected", error: reason)
    }
}

/// Per-WebView session guard. Nonces are generated by the native host and
/// request IDs are retained to prevent replay during the lifetime of a session.
public actor BridgeSession {
    public let nonce: String
    private var consumedRequestIDs = Set<UUID>()
    private let maximumRememberedRequests: Int

    public init(maximumRememberedRequests: Int = 2_048) {
        self.nonce = UUID().uuidString + UUID().uuidString
        self.maximumRememberedRequests = max(32, maximumRememberedRequests)
    }

    public func validateAndConsume(_ request: BridgeRequest) -> Bool {
        guard request.version == 1, request.nonce == nonce else { return false }
        guard !consumedRequestIDs.contains(request.requestID) else { return false }
        guard consumedRequestIDs.count < maximumRememberedRequests else { return false }
        consumedRequestIDs.insert(request.requestID)
        return true
    }
}
